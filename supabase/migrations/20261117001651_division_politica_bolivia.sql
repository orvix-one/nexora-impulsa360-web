-- Official political-administrative division of Bolivia: departamento > provincia > municipio, keyed by INE code (2 + 2 + 2 digits).
-- Source: OCHA COD-AB Bolivia, valid_on 2024-09-16, from the Ministerio de Desarrollo Rural y Tierras (data.humdata.org/dataset/cod-ab-bol); codigo_ine = P-code without 'BO'.

CREATE TABLE public.departamentos (
    id smallint PRIMARY KEY,
    codigo_ine text NOT NULL UNIQUE,
    nombre text NOT NULL
);

CREATE TABLE public.provincias (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    departamento_id smallint NOT NULL REFERENCES public.departamentos(id),
    codigo_ine text NOT NULL UNIQUE,
    nombre text NOT NULL
);

CREATE TABLE public.municipios (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    provincia_id integer NOT NULL REFERENCES public.provincias(id),
    codigo_ine text NOT NULL UNIQUE,
    nombre text NOT NULL
);

CREATE INDEX idx_provincias_departamento ON public.provincias USING btree (departamento_id);
CREATE INDEX idx_municipios_provincia ON public.municipios USING btree (provincia_id);

ALTER TABLE public.departamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.provincias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.municipios ENABLE ROW LEVEL SECURITY;

