-- Neighbourhood (barrio) of each activation. Catalog of named points: OpenStreetMap place=suburb|neighbourhood|quarter,
-- plus names that 3 different activators typed near each other. No polygons exist, so the app shows the nearest barrio
-- when it is clearly the closest and asks otherwise (same rule in zona_sugerida and impulsa360-mobile/lib/zonas.js).
-- OSM source: Overpass API, osm_base 2026-11-18T19:18:18Z, query nwr(area["ISO3166-1"="BO"])["place"~"^(suburb|neighbourhood|quarter)$"]; out center;
-- names starting with "distrito"/"macrodistrito" excluded.

create table public.zonas (
  id integer generated always as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  nombre_normalizado text not null,
  municipio_id integer not null references public.municipios(id),
  municipio_nombre text not null,
  latitud double precision not null,
  longitud double precision not null,
  punto extensions.geography generated always as
    (extensions.st_setsrid(extensions.st_makepoint(longitud, latitud), 4326)::extensions.geography) stored,
  fuente text not null check (fuente in ('osm', 'activadores')),
  osm_ref text,
  activa boolean not null default true,
  created_at timestamptz not null default now(),
  unique (municipio_id, nombre_normalizado)
);

create index idx_zonas_punto on public.zonas using gist (punto);
alter table public.zonas enable row level security;

create function public.normalizar_zona(p_nombre text) returns text
  language sql stable
  set search_path = ''
as $$
  select lower(public.unaccent(regexp_replace(btrim(coalesce(p_nombre, '')), '\s+', ' ', 'g')))
$$;

create function public.completar_zona() returns trigger
  language plpgsql
  set search_path = ''
as $$
begin
  new.nombre := regexp_replace(btrim(new.nombre), '\s+', ' ', 'g');
  new.nombre_normalizado := public.normalizar_zona(new.nombre);
  new.municipio_id := coalesce(new.municipio_id, public.municipio_en_punto(new.latitud, new.longitud));
  select coalesce(m.nombre_comun, m.nombre) into new.municipio_nombre from public.municipios m where m.id = new.municipio_id;
  return new;
end;
$$;

create trigger trg_completar_zona
  before insert or update of nombre, latitud, longitud, municipio_id on public.zonas
  for each row execute function public.completar_zona();

revoke all on function public.normalizar_zona(text), public.completar_zona() from public, anon, authenticated;

