insert into public.zonas (nombre, municipio_id, latitud, longitud, fuente, osm_ref)
select o.nombre, m.municipio_id, o.latitud, o.longitud, 'osm', o.osm_ref
from osm o
cross join lateral (select public.municipio_en_punto(o.latitud, o.longitud) as municipio_id) m
where m.municipio_id is not null
on conflict (municipio_id, nombre_normalizado) do nothing;

-- Clearly the closest: within 250 m and the next barrio at least 1.5 times farther.
create function public.zona_sugerida(p_latitud double precision, p_longitud double precision)
  returns table (zona_id integer, distancia_m double precision, cierta boolean)
  language sql stable
  set search_path = ''
as $$
  with punto as (
    select extensions.st_setsrid(extensions.st_makepoint(p_longitud, p_latitud), 4326)::extensions.geography as g
  ), cercanas as (
    select z.id, extensions.st_distance(z.punto, p.g) as d, row_number() over (order by extensions.st_distance(z.punto, p.g)) as n
    from public.zonas z, punto p
    where z.activa and extensions.st_dwithin(z.punto, p.g, 3000)
  )
  select c1.id, c1.d, c1.d <= 250 and (c2.d is null or c2.d >= 1.5 * c1.d)
  from cercanas c1 left join cercanas c2 on c2.n = 2
  where c1.n = 1
$$;

