-- SECURITY DEFINER because the app inserts as authenticated; fires after trg_ubicar_activacion (triggers run by name), which sets municipio_id.
create function public.asignar_zona_activacion() returns trigger
  language plpgsql
  security definer
  set search_path = ''
as $$
declare
  v_zona public.zonas%rowtype;
begin
  -- Updates: the portal edits the text (zona_id is dropped) and promover_zona links typed rows to a new barrio.
  if tg_op = 'UPDATE' then
    if new.zona_id is distinct from old.zona_id then return new; end if;
    if new.zona_activacion is distinct from old.zona_activacion then
      new.zona_id := null;
      new.zona_fuente := case when nullif(btrim(new.zona_activacion), '') is null then null else 'escrita' end;
    end if;
    return new;
  end if;

  if new.zona_id is not null then
    select * into v_zona from public.zonas where id = new.zona_id;
    if v_zona.id is not null then
      new.zona_activacion := v_zona.nombre;
      new.zona_fuente := case when new.zona_fuente = 'gps' then 'gps' else 'elegida' end;
      return new;
    end if;
    new.zona_id := null;
  end if;

  if nullif(btrim(new.zona_activacion), '') is not null then
    new.zona_activacion := regexp_replace(btrim(new.zona_activacion), '\s+', ' ', 'g');
    new.zona_fuente := 'escrita';
    select z.id into new.zona_id from public.zonas z
    where z.municipio_id = new.municipio_id and z.nombre_normalizado = public.normalizar_zona(new.zona_activacion);
    return new;
  end if;

  -- Builds that send no zone get the nearest barrio within 500 m.
  select s.zona_id into new.zona_id from public.zona_sugerida(new.latitud, new.longitud) s where s.distancia_m <= 500;
  if new.zona_id is not null then
    select z.nombre into new.zona_activacion from public.zonas z where z.id = new.zona_id;
    new.zona_fuente := 'gps';
  else
    new.zona_activacion := null;
    new.zona_fuente := null;
  end if;
  return new;
end;
$$;

create trigger trg_zona_activacion
  before insert or update of zona_activacion, zona_id on public.activaciones
  for each row execute function public.asignar_zona_activacion();

-- A typed name becomes a catalog barrio once 3 different activators typed it in the same municipio within 1 km.
create function public.promover_zona(p_activacion_id uuid) returns void
  language plpgsql
  security definer
  set search_path = ''
as $$
declare
  v_base public.activaciones%rowtype;
  v_zona integer;
begin
  select * into v_base from public.activaciones where id = p_activacion_id;
  if v_base.zona_id is not null or v_base.zona_fuente <> 'escrita' or v_base.municipio_id is null then return; end if;

  create temp table if not exists iguales (id uuid, usuario_id uuid, latitud double precision, longitud double precision) on commit drop;
  truncate iguales;
  insert into iguales
  select a.id, a.usuario_id, a.latitud, a.longitud from public.activaciones a
  where a.municipio_id = v_base.municipio_id and a.zona_id is null and a.zona_fuente = 'escrita'
    and public.normalizar_zona(a.zona_activacion) = public.normalizar_zona(v_base.zona_activacion)
    and extensions.st_dwithin(
      extensions.st_setsrid(extensions.st_makepoint(a.longitud, a.latitud), 4326)::extensions.geography,
      extensions.st_setsrid(extensions.st_makepoint(v_base.longitud, v_base.latitud), 4326)::extensions.geography,
      1000);
  if (select count(distinct usuario_id) from iguales) < 3 then return; end if;

  insert into public.zonas (nombre, municipio_id, latitud, longitud, fuente)
  select v_base.zona_activacion, v_base.municipio_id,
    percentile_cont(0.5) within group (order by latitud), percentile_cont(0.5) within group (order by longitud), 'activadores'
  from iguales
  on conflict (municipio_id, nombre_normalizado) do nothing
  returning id into v_zona;

  if v_zona is not null then
    update public.activaciones set zona_id = v_zona where id in (select id from iguales);
  end if;
end;
$$;

create function public.promover_zona_activacion() returns trigger
  language plpgsql
  security definer
  set search_path = ''
as $$
begin
  if new.zona_fuente = 'escrita' and new.zona_id is null then perform public.promover_zona(new.id); end if;
  return null;
end;
$$;

create trigger trg_promover_zona
  after insert on public.activaciones
  for each row execute function public.promover_zona_activacion();

revoke all on function public.zona_sugerida(double precision, double precision), public.asignar_zona_activacion(),
  public.promover_zona(uuid), public.promover_zona_activacion() from public, anon, authenticated;

-- History: zones typed before 1.0.36 keep their text. Names typed by 3+ activators in a municipio seed the catalog,
-- except the old app's district/macrodistrict lists in the big cities (the bank wants barrios).
insert into public.zonas (nombre, municipio_id, latitud, longitud, fuente)
select (array_agg(a.zona_activacion order by a.created_at))[1], a.municipio_id,
  percentile_cont(0.5) within group (order by a.latitud), percentile_cont(0.5) within group (order by a.longitud), 'activadores'
from public.activaciones a
join public.municipios m on m.id = a.municipio_id
where nullif(btrim(a.zona_activacion), '') is not null
  and public.normalizar_zona(a.zona_activacion) not in ('otro', 'otros', public.normalizar_zona(coalesce(m.nombre_comun, m.nombre)))
  and public.normalizar_zona(a.zona_activacion) !~ '(^|\s)(macro)?distrito'
  and not (m.codigo_ine in ('020101', '020105', '070101', '030101', '040101', '010101')
    and public.normalizar_zona(a.zona_activacion) in (
      'centro', 'cotahuma', 'mallasa', 'max paredes', 'periferica', 'san antonio', 'sur', 'norte', 'este', 'oeste', 'central',
      'sacaba', 'quillacollo', 'tiquipaya', 'cercado', 'la guardia', 'el torno', 'samaipata', 'san julian', '4 canadas',
      'paurito', 'concepcion', 'bbo'))
group by a.municipio_id, public.normalizar_zona(a.zona_activacion)
having count(distinct a.usuario_id) >= 3
on conflict (municipio_id, nombre_normalizado) do nothing;

alter table public.activaciones disable trigger trg_zona_activacion;

update public.activaciones a
set zona_fuente = 'escrita',
  zona_id = (select z.id from public.zonas z where z.municipio_id = a.municipio_id and z.nombre_normalizado = public.normalizar_zona(a.zona_activacion))
where nullif(btrim(a.zona_activacion), '') is not null;

update public.activaciones a
set zona_id = s.zona_id, zona_fuente = 'gps', zona_activacion = z.nombre
from public.activaciones x
cross join lateral public.zona_sugerida(x.latitud, x.longitud) s
join public.zonas z on z.id = s.zona_id
where a.id = x.id and nullif(btrim(x.zona_activacion), '') is null and s.distancia_m <= 500;

